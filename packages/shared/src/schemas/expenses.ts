import { z } from 'zod';
import {
  EXPENSE_PAYMENT_METHODS,
  type CashMovementType,
  type ExpensePaymentMethod,
} from '../constants';
import { isIsoDate, type IsoDate } from '../dates';

const madAmount = z
  .string()
  .trim()
  .regex(/^\d+([.,]\d{1,2})?$/, 'invalid_amount');
const positiveMad = madAmount.refine((v) => Number(v.replace(',', '.')) > 0, 'invalid_amount');
const optionalMad = madAmount.optional().or(z.literal('').transform(() => undefined));
const optionalText = (max: number) =>
  z
    .string()
    .trim()
    .max(max)
    .optional()
    .transform((v) => (v ? v : undefined));

/** Quick add: amount + category are the only required fields. */
export const expenseFormSchema = z.object({
  amountMad: positiveMad,
  categoryId: z.string().uuid('required'),
  supplierName: optionalText(120),
  date: z.string().refine(isIsoDate, 'invalid_date'),
  tvaMad: optionalMad,
  note: optionalText(500),
  paymentMethod: z.enum(EXPENSE_PAYMENT_METHODS),
  walletId: optionalText(36),
});
export type ExpenseFormInput = z.infer<typeof expenseFormSchema>;

export const recurringFormSchema = z.object({
  label: z.string().trim().min(1).max(120),
  categoryId: z.string().uuid('required'),
  amountMad: positiveMad,
  dayOfMonth: z.coerce.number().int().min(1).max(31),
  paymentMethod: z.enum(EXPENSE_PAYMENT_METHODS),
  supplierName: optionalText(120),
});
export type RecurringFormInput = z.infer<typeof recurringFormSchema>;

export const supplierFormSchema = z.object({
  name: z.string().trim().min(1).max(120),
  defaultCategoryId: optionalText(36),
  phone: optionalText(40),
});

export const walletAmountSchema = z.object({ amountMad: positiveMad, note: optionalText(200) });

export type ExpenseCategoryDto = {
  id: string;
  key: string | null;
  nameFr: string;
  nameAr: string;
  icon: string;
};

export type SupplierDto = {
  id: string;
  name: string;
  phone: string | null;
  defaultCategoryId: string | null;
  expenseCount: number;
};

type Ref = { id: string; name: string };

export type ExpenseDto = {
  id: string;
  amountTtc: number;
  tvaAmount: number;
  date: IsoDate;
  paymentMethod: ExpensePaymentMethod;
  note: string | null;
  category: ExpenseCategoryDto;
  supplier: Ref | null;
  wallet: Ref | null;
  createdBy: Ref | null;
  hasReceipt: boolean;
  /** Generated by a recurring expense / by payroll (read-only in the UI). */
  source: 'MANUAL' | 'RECURRING' | 'PAYROLL';
  createdAt: string;
};

export type ExpenseListDto = {
  items: ExpenseDto[];
  page: number;
  limit: number;
  total: number;
  /** Over every page of the filtered period, not just this one. */
  sumTtc: number;
  sumTva: number;
  byCategory: { categoryId: string; amount: number }[];
};

export type CashWalletDto = {
  id: string;
  name: string;
  balance: number;
  isActive: boolean;
  holder: Ref;
};

export type CashMovementDto = {
  id: string;
  type: CashMovementType;
  amount: number;
  note: string | null;
  createdAt: string;
  createdBy: Ref | null;
  expense: { id: string; category: string; categoryKey: string | null; supplier: string | null } | null;
  /** Guest cash payment received into the box. */
  payment: { id: string; stayId: string; guestName: string | null; roomName: string | null } | null;
  /** Box balance right after this movement (centimes). */
  balanceAfter: number;
};

/** A cash box's movements over a period, with what came in and went out (centimes). */
export type CashBoxReportDto = {
  items: CashMovementDto[];
  total: number;
  page: number;
  limit: number;
  totals: { in: number; out: number; byType: Record<CashMovementType, number> };
};

export type RecurringExpenseDto = {
  id: string;
  label: string;
  amount: number;
  dayOfMonth: number;
  paymentMethod: ExpensePaymentMethod;
  isActive: boolean;
  category: ExpenseCategoryDto;
  supplier: Ref | null;
  nextDate: IsoDate;
  lastGenerated: IsoDate | null;
};
